public class dataTypes {
    public static void main(String[] args) {
        //integer data types
        byte b= 10;
        short year= 100;
        int salary= 100000;
        long population= 1000000000;

        //floating point data types
        float per= 93.14f;
        double pi= 2.718281828459045;

        //character data type
        char grade= 'A';

        //boolean data type
        boolean ispass= true; //default value of boolean is false
        
        System.out.println("primitive data types ");
        System.out.println("\nbyte: " + b);
        System.out.println("short: " + year);
        System.out.println("int: " + salary);
        System.out.println("long: " + population);

        System.out.println("\nfloat: " + per);
        System.out.println("\ndouble: " + pi);

        System.out.println("\nchar: " + grade);

        System.out.println("\nboolean: " + ispass);




    }
}